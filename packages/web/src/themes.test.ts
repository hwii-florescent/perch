// @vitest-environment jsdom
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { applyTheme, backdropFor, lookVars, paletteFromFile, PERCH_DEFAULT, registerThemes, resolveTheme, setRootLook, themeName, THEMES, THEME_NAMES } from "./themes";
import catppuccin from "./palettes/catppuccin.json";
import resolvedBeforePaletteImport from "./__fixtures__/themes.resolved.json";

// Independent WCAG calculation: test the resolved colors, not the adapter's
// own contrast function (nor a relative comparison that lets both be dim).
const lum = (hex: string) => [0.2126, 0.7152, 0.0722].reduce((sum, weight, i) => {
  const v = parseInt(hex.slice(1 + 2 * i, 3 + 2 * i), 16) / 255;
  return sum + weight * (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
}, 0);
const contrast = (a: string, b: string) => (Math.max(lum(a), lum(b)) + 0.05) / (Math.min(lum(a), lum(b)) + 0.05);
const lightThemes = ["catppuccin-latte", "tokyo-night-day", "gruvbox-light", "one-light", "solarized-light", "kanagawa-lotus", "rose-pine-dawn"];

describe.each(Object.keys(THEMES))("%s theme", (name) => {
  it("keeps text, icons, statuses and links readable on every chrome surface", () => {
    const p = resolveTheme(name);
    for (const fg of [p.text, p.subtext0, p.overlay1, p.accent, p.mauve, p.green, p.yellow, p.red, p.blue, p.teal, p.peach]) {
      for (const bg of [p.panelBg, p.surface0, p.surface1, p.surfaceDim]) {
        expect(contrast(fg, bg), `${name}: ${fg} on ${bg}`).toBeGreaterThanOrEqual(4.5);
      }
    }
    // The same pair is used in reverse by filled buttons and checked switches.
    for (const fill of [p.accent, p.red, p.green]) {
      expect(contrast(p.panelBg, fill)).toBeGreaterThanOrEqual(4.5);
    }
  });

  it("preserves source colors and never changes backgrounds to fix text", () => {
    const source = THEMES[name]!;
    const before = { ...source };
    const p = resolveTheme(name);
    expect(source).toEqual(before);
    for (const key of ["panelBg", "surface0", "surface1", "surfaceDim", "overlay0"] as const) {
      expect(p[key]).toBe(source[key]);
    }
    for (const value of Object.values(source)) expect(value).toMatch(/^#[0-9a-f]{6}$/);
    // Colors already meeting the floor must stay exactly upstream.
    if ([source.panelBg, source.surface0, source.surface1, source.surfaceDim].every((bg) => contrast(source.accent, bg) >= 4.5)) {
      expect(p.accent).toBe(source.accent);
    }
  });

  it("applies all tokens and native control appearance without stale colors", () => {
    applyTheme(name);
    const p = resolveTheme(name);
    const style = document.documentElement.style;
    expect(style.getPropertyValue("--panel-bg")).toBe(p.panelBg);
    expect(style.getPropertyValue("--text")).toBe(p.text);
    expect(style.getPropertyValue("--green")).toBe(p.green);
    expect(style.getPropertyValue("--accent")).toBe(p.accent);
    expect(style.getPropertyValue("--backdrop")).toBe(backdropFor(p));
    expect(style.getPropertyValue("color-scheme")).toBe(lightThemes.includes(name) ? "light" : "dark");
  });
});

it.each(THEME_NAMES)("%s: the derived backdrop separates from the cards without being the card color", (name) => {
  const p = resolveTheme(name);
  const backdrop = backdropFor(p);
  expect(backdrop).toMatch(/^#[0-9a-f]{6}$/);
  expect(backdrop).not.toBe(p.panelBg);
  expect(contrast(backdrop, p.panelBg)).toBeGreaterThanOrEqual(1.12);
  // Light themes get a slightly darker backdrop, dark themes a darker one: never brighter than a light card.
  if (lightThemes.includes(name)) expect(lum(backdrop)).toBeLessThan(lum(p.panelBg));
});

it("keeps the pinned Catppuccin colors intact and maps the existing surface roles", () => {
  expect(catppuccin.source).toBe("https://raw.githubusercontent.com/catppuccin/palette/07d02aa110ef9eb7e7427afca5c73ba9cf7f8ebd/palette.json");
  expect(catppuccin.sha256).toBe("4bc114bb6b3c9a9c9e156564aa84625aef32c5da514d9dd431cf1fcad433a05f");
  expect(createHash("sha256").update(JSON.stringify(catppuccin.colors)).digest("hex"))
    .toBe("1a7dda0d9f5b2d40d8f50271e0fb980be26d1d045c27b46b74b4ae9e7749cbef");
  for (const colors of Object.values(catppuccin.colors)) {
    expect(Object.keys(colors)).toHaveLength(26);
    for (const hex of Object.values(colors)) expect(hex).toMatch(/^#[0-9a-f]{6}$/);
  }
  expect(THEMES.catppuccin?.panelBg).toBe(catppuccin.colors.mocha.mantle);
  expect(THEMES["catppuccin-latte"]?.panelBg).toBe(catppuccin.colors.latte.base);
  expect(THEMES["catppuccin-latte"]?.surface0).toBe(catppuccin.colors.latte.mantle);
  expect(THEMES["catppuccin-latte"]?.surface1).toBe(catppuccin.colors.latte.surface0);
});

it("preserves every resolved palette and the persisted theme names/order from before the import", () => {
  // Captured before the refactor at 2ff7736; never regenerated by this test.
  expect(THEME_NAMES).toEqual(Object.keys(resolvedBeforePaletteImport));
  expect(Object.fromEntries(THEME_NAMES.map((name) => [name, resolveTheme(name)])))
    .toEqual(resolvedBeforePaletteImport);
});

it("retains upstream identity colors and correct UI background/foreground mappings", () => {
  expect(THEMES.catppuccin?.accent).toBe("#89b4fa");
  expect(THEMES.dracula?.surface1).toBe("#44475a"); // selection, not comment blue
  expect(THEMES.solarized?.surface1).toBe("#004454"); // UI hover, not base01 text
  expect(THEMES.vesper?.panelBg).toBe("#101010");
  expect(THEMES["rose-pine-dawn"]?.text).toBe("#575279");
  expect(THEMES["rose-pine"]?.peach).toBe("#ebbcba");
  expect(THEMES["tokyo-night-day"]?.text).toBe("#343b59");
});

it("unknown names (including inherited object keys) fall back and reset light appearance", () => {
  for (const name of ["", "missing", "__proto__", "toString"]) {
    applyTheme("one-light");
    applyTheme(name);
    expect(resolveTheme(name)).toEqual(resolveTheme("perch"));
    expect(document.documentElement.style.getPropertyValue("color-scheme")).toBe("dark");
  }
});

it("the CSS defaults agree with the resolved neutral palette", () => {
  const { colorScheme, ...resolved } = resolveTheme("perch");
  expect(colorScheme).toBe("dark");
  expect(resolved).toEqual(PERCH_DEFAULT);
  const css = readFileSync("src/styles/base.css", "utf8");
  for (const [key, value] of Object.entries(PERCH_DEFAULT)) {
    const token = key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/([a-z])(\d)/g, "$1-$2");
    expect(css).toContain(`--${token}: ${value};`);
  }
});

it("a layout look sets the theme's tokens, single color overrides and the derived ones below <html>", () => {
  const vars = lookVars({ theme: "nord", colors: { accent: "#ff8800", backdrop: "#101010", bogus: "#000000" }, font: "Geist", radius: 4, border: 1 }, true);
  expect(vars["--accent"]).toBe("#ff8800");
  expect(vars["--backdrop"]).toBe("#101010");
  expect(vars["--panel-bg"]).toBe(resolveTheme("nord").panelBg);
  expect(vars["--card-bg"]).toBe(vars["--panel-bg"]); // base.css derives it at :root, so a node must set it
  expect(vars["--surface"]).toBe(vars["--surface-0"]);
  expect([vars["--font-ui"], vars["--card-radius"], vars["--card-border"]]).toEqual(["Geist", "4px", "1px"]);
  expect(Object.keys(vars).some((name) => name.includes("bogus"))).toBe(false);
  expect(lookVars({ radius: 0 }, true)).toEqual({ "--card-radius": "0px" }); // no theme: nothing inherited is touched
  expect(lookVars({ theme: "nord" }, false)["--card-bg"]).toBeUndefined();
});

it("the root look stays on top when the settings theme is applied again, and is undone", () => {
  const root = document.documentElement.style;
  applyTheme("perch");
  setRootLook(lookVars({ colors: { accent: "#ff8800" }, radius: 2 }, false));
  applyTheme("perch"); // any settings message does this
  expect(root.getPropertyValue("--accent")).toBe("#ff8800");
  expect(root.getPropertyValue("--card-radius")).toBe("2px");
  setRootLook({});
  expect(root.getPropertyValue("--accent")).toBe(resolveTheme("perch").accent);
  expect(root.getPropertyValue("--card-radius")).toBe("");
});

describe("theme files", () => {
  const ansi = Array.from({ length: 16 }, (_, i) => `#${(i * 15).toString(16).padStart(2, "0").repeat(3)}`);
  it("derive a palette from herdr's terminal shape or from Perch's own, and are offered by file name", () => {
    const term = paletteFromFile({ background: "#101010", foreground: "#eeeeee", ansi })!;
    expect([term.panelBg, term.text, term.red, term.green]).toEqual(["#101010", "#eeeeee", ansi[1], ansi[2]]);
    expect(term.surface0).not.toBe(term.panelBg);
    const mine = paletteFromFile({ base: "catppuccin", colors: { accent: "#ff8800" } })!;
    expect([mine.accent, mine.panelBg]).toEqual(["#ff8800", THEMES.catppuccin!.panelBg]);
    expect(paletteFromFile({})).toBeNull();

    registerThemes([
      { id: "dusk", name: "Dusk", theme: { background: "#101010", foreground: "#eeeeee", ansi }, error: null },
      { id: "perch", name: "Perch", theme: { colors: { accent: "#ff8800" } }, error: null }, // a shipped name stays shipped
      { id: "broken", name: "broken", theme: null, error: "colors are #rrggbb" },
    ]);
    expect(THEME_NAMES).toContain("dusk");
    expect(THEME_NAMES).not.toContain("broken");
    expect(THEMES.perch).toBe(PERCH_DEFAULT);
    expect(resolveTheme("dusk").panelBg).toBe("#101010");
    registerThemes([]); // a removed file stops being offered
    expect(THEME_NAMES).not.toContain("dusk");
    expect(Object.hasOwn(THEMES, "dusk")).toBe(false);
  });

  it("take herdr's win98 theme as shipped: its terminal colors, then its named colors on top", () => {
    const win98 = {
      background: "#ffffff", foreground: "#c0c0c0", selection: "#000080", cursor: "#c0c0c0",
      ansi: ["#555555", "#aa0000", "#00aa00", "#aa5500", "#0000bb", "#aa00aa", "#00aaaa", "#aaaaaa", "#555555", "#ff5555", "#55ff55", "#ffff55", "#5555ff", "#ff55ff", "#55ffff", "#ffffff"],
      colors: { background: "#000000", foreground: "#000000", surface: "#c0c0c0", raised: "#dfdfdf", border: "#808080", muted: "#404040", accent: "#000080", ring: "#000000", working: "#808000", blocked: "#ff0000", __proto__x: "#123456" },
    };
    const palette = paletteFromFile(win98)!;
    expect([palette.panelBg, palette.surface0, palette.overlay0, palette.subtext0, palette.text, palette.accent, palette.yellow, palette.red])
      .toEqual(["#c0c0c0", "#dfdfdf", "#808080", "#404040", "#000000", "#000080", "#808000", "#ff0000"]);
    expect(palette.green).toBe("#00aa00"); // from the ANSI colors
    expect(Object.keys(palette).sort()).toEqual(Object.keys(PERCH_DEFAULT).sort()); // nothing foreign leaks in
  });

  it("picks a half of a light/dark pair", () => {
    expect(themeName("nord", true)).toBe("nord");
    expect(themeName({ light: "paper", dark: "nord" }, true)).toBe("nord");
    expect(themeName({ light: "paper", dark: "nord" }, false)).toBe("paper");
    expect(themeName(undefined, true)).toBeUndefined();
  });
});
