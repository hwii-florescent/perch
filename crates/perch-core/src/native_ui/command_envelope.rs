//! What Claude's transcript writes for a slash command or a `!` shell line, and what the chat does
//! with it. Claude records those as user rows holding harness tags (`<command-name>`,
//! `<local-command-stdout>`, `<bash-input>`), which must neither show as the person's words nor
//! hide a skill invocation, whose reply would otherwise have no prompt above it.
//!
//! Ported from Orca (commit 308b5000, MIT; see THIRD_PARTY_NOTICES.md):
//! `src/shared/native-chat/native-chat-command-envelope.ts` (envelope parse and the
//! catalog-versus-skill split, `surfaceSkillInvocationUserTurns`), `src/shared/
//! harness-injected-user-turns.ts` (which user text is harness machinery) and `src/shared/
//! claude-bash-input.ts`, with their tests. Orca's `surfaceNativeChatCommandOutputs` (answers of
//! reporting commands such as `/context`) is not ported: those outputs stay hidden with the rest.

/// A parsed `<command-name>`/`<command-args>` envelope.
#[derive(Debug, PartialEq, Eq)]
pub struct Envelope {
    pub name: String,
    pub args: String,
}

/// What the chat does with one user row of the transcript.
#[derive(Debug, PartialEq, Eq)]
pub enum UserTurn {
    /// An ordinary prompt: shown as written.
    Keep,
    /// Harness machinery: not shown. A built-in command's own feedback is the "Ran /x" notice.
    Hidden,
    /// Shown as this text instead: a skill invocation as the person typed it, a `!` line.
    Shown(String),
}

fn between<'a>(text: &'a str, tag: &str) -> Option<&'a str> {
    let open = format!("<{tag}>");
    let from = text.find(&open)? + open.len();
    let to = from + text[from..].find(&format!("</{tag}>"))?;
    Some(&text[from..to])
}

/// Only a leading envelope counts, so an ordinary prompt that quotes the tags stays literal.
pub fn parse_envelope(text: &str) -> Option<Envelope> {
    let trimmed = text.trim_start();
    if !trimmed
        .get(..9)
        .is_some_and(|head| head.eq_ignore_ascii_case("<command-"))
    {
        return None;
    }
    let name = between(trimmed, "command-name")?.trim();
    (!name.is_empty()).then(|| Envelope {
        name: name.to_string(),
        args: between(trimmed, "command-args")
            .map_or("", str::trim)
            .to_string(),
    })
}

const KNOWN_HARNESS_TAGS: &[&str] = &[
    "agent-message",
    "bash-input",
    "bash-stderr",
    "bash-stdout",
    "command-args",
    "command-message",
    "command-name",
    "cross-session-message",
    "fork-boilerplate",
    "local-command-caveat",
    "local-command-stderr",
    "local-command-stdout",
    "mcp-polling-update",
    "mcp-resource-update",
    "system-reminder",
    "task-notification",
    "teammate-message",
    "user-memory-input",
    "user-prompt-submit-hook",
];

/// Matched on lowercased text. A bare `<channel>` is legitimate XML; only the attributed form counts.
const HARNESS_PREFIXES: &[&str] = &[
    "<channel source=",
    "[request interrupted",
    "a message arrived from ",
    "another claude session sent a message",
    "no response requested.",
    "caveat: the messages below were generated by the user while running local commands",
    "this session is being continued from a previous conversation",
];

/// Bounds the lowercasing so a large paste costs the same as a short prompt.
const HEAD_LIMIT: usize = 256;
const LEADING_WHITESPACE_LIMIT: usize = 64;

fn head(text: &str) -> String {
    let bytes = text.as_bytes();
    let mut start = 0;
    while start < bytes.len().min(LEADING_WHITESPACE_LIMIT)
        && matches!(bytes[start], b' ' | b'\t' | b'\n' | b'\r' | 0x0c)
    {
        start += 1;
    }
    text[start..]
        .chars()
        .take(HEAD_LIMIT)
        .collect::<String>()
        .to_lowercase()
}

/// The tag name when the text starts with `<name>`, `<name ` or `<name` and nothing else.
fn leading_tag(head: &str) -> Option<&str> {
    let rest = head.strip_prefix('<')?;
    if !rest.starts_with(|ch: char| ch.is_ascii_lowercase()) {
        return None;
    }
    let end = rest
        .find(|ch: char| !(ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '-'))
        .unwrap_or(rest.len());
    let after = rest[end..].chars().next();
    (after.is_none_or(|ch| ch.is_whitespace() || ch == '>')).then(|| &rest[..end])
}

/// Only observed harness shapes: an unknown tag is the person's own text.
pub fn is_harness_injected(text: &str) -> bool {
    let head = head(text);
    if head.is_empty() {
        return false;
    }
    leading_tag(&head).is_some_and(|tag| KNOWN_HARNESS_TAGS.contains(&tag))
        || HARNESS_PREFIXES
            .iter()
            .any(|prefix| head.starts_with(prefix))
}

/// `<bash-input>ls</bash-input>` back to the line as typed (`!ls`), `None` for any other text.
/// Claude strips the `!` and keeps the space after it.
pub fn bash_input_as_typed(text: &str) -> Option<String> {
    let inner = text
        .trim()
        .strip_prefix("<bash-input>")?
        .strip_suffix("</bash-input>")?;
    (!inner.contains("<bash-input>")).then(|| format!("!{inner}"))
}

/// Classify one user row's text. `is_builtin` says whether a command name is one of the CLI's own
/// (a skill or plugin command is not: its reply needs the prompt that started it).
pub fn classify(text: &str, is_builtin: &dyn Fn(&str) -> bool) -> UserTurn {
    if let Some(typed) = bash_input_as_typed(text) {
        return UserTurn::Shown(typed);
    }
    if let Some(envelope) = parse_envelope(text) {
        let name = envelope.name.trim_start_matches('/');
        if is_builtin(name) {
            return UserTurn::Hidden;
        }
        // A plugin's envelope names `/plugin:name`; the person typed the short name.
        let token = format!("/{}", name.rsplit(':').next().unwrap_or(name));
        return UserTurn::Shown(if envelope.args.is_empty() {
            token
        } else {
            format!("{token} {}", envelope.args)
        });
    }
    if is_harness_injected(text) {
        UserTurn::Hidden
    } else {
        UserTurn::Keep
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn catalog(name: &str) -> bool {
        matches!(name, "clear" | "model")
    }

    fn envelope(name: &str, args: &str) -> Option<Envelope> {
        Some(Envelope {
            name: name.into(),
            args: args.into(),
        })
    }

    #[test]
    fn parses_name_first_and_message_first_envelopes() {
        assert_eq!(
            parse_envelope("<command-name>/model</command-name>\n  <command-message>model</command-message>\n  <command-args></command-args>"),
            envelope("/model", "")
        );
        assert_eq!(
            parse_envelope("<command-message>ce-brainstorm</command-message>\n<command-name>/ce-brainstorm</command-name>\n<command-args>improve the picker</command-args>"),
            envelope("/ce-brainstorm", "improve the picker")
        );
    }

    #[test]
    fn ignores_ordinary_prompts_and_non_leading_envelope_tags() {
        assert_eq!(parse_envelope("deploy the app"), None);
        assert_eq!(parse_envelope("see <command-name>/x</command-name>"), None);
        assert_eq!(parse_envelope("<commander>/x</commander>"), None);
    }

    #[test]
    fn a_plugin_skill_shows_as_the_short_token_the_person_typed() {
        assert_eq!(
            classify("<command-message>compound-engineering:ce-brainstorm</command-message>\n<command-name>/compound-engineering:ce-brainstorm</command-name>\n<command-args>hi</command-args>", &catalog),
            UserTurn::Shown("/ce-brainstorm hi".into())
        );
    }

    #[test]
    fn a_plugin_skill_that_shadows_a_catalog_name_is_never_hidden() {
        assert_eq!(
            classify(
                "<command-name>/some-plugin:clear</command-name>\n<command-args></command-args>",
                &catalog
            ),
            UserTurn::Shown("/clear".into())
        );
    }

    #[test]
    fn a_catalog_command_envelope_is_hidden_behind_the_ran_notice() {
        assert_eq!(
            classify(
                "<command-name>/model</command-name>\n<command-args></command-args>",
                &catalog
            ),
            UserTurn::Hidden
        );
    }

    // Shapes seen in Claude 2.1.318 transcripts: a skill, and a built-in with its own output row.
    #[test]
    fn real_transcript_rows() {
        assert_eq!(
            classify(
                "<command-message>perchping</command-message>\n<command-name>/perchping</command-name>",
                &catalog
            ),
            UserTurn::Shown("/perchping".into())
        );
        assert_eq!(
            classify(
                "<local-command-stdout>Enabled plan mode</local-command-stdout>",
                &catalog
            ),
            UserTurn::Hidden
        );
    }

    #[test]
    fn matches_every_known_harness_tag_including_attribute_forms() {
        for text in [
            "<task-notification> <task-id>bzthj2b8r</task-id> <tool-use-id>toolu_01abc</tool-use-id>",
            "<task-notification summary=\"Agent finished\">",
            "<system-reminder>context</system-reminder>",
            "<agent-message from=\"reviewer-A-r3b\"> REVIEW the diff",
            "<teammate-message teammate_id=\"worker-1\">status?",
            "<cross-session-message from=\"other session\">hello",
            "<channel source=\"general\">new post",
            "<fork-boilerplate>Your directive: ship it",
            "<user-memory-input>remember this",
            "<mcp-resource-update uri=\"db://x\">",
            "<mcp-polling-update>tick",
            "<command-name>/review</command-name>",
            "<command-message>review</command-message>",
            "<command-args>--fix</command-args>",
            "<local-command-stdout>ok</local-command-stdout>",
            "<local-command-stderr>boom</local-command-stderr>",
            "<local-command-caveat>Caveat: tool output</local-command-caveat>",
            "<bash-input>ls</bash-input>",
            "<bash-stdout>file.txt</bash-stdout>",
            "<bash-stderr>err</bash-stderr>",
            "<user-prompt-submit-hook>hook context</user-prompt-submit-hook>",
        ] {
            assert!(is_harness_injected(text), "{text}");
        }
    }

    #[test]
    fn matches_harness_prose_wrappers_and_notices() {
        for text in [
            "A message arrived from teammate-b:\n<agent-message>hi",
            "Another Claude session sent a message:\n<agent-message>hi",
            "No response requested.",
            "[Request interrupted by user]",
            "[Request interrupted by user for tool use]",
            "This session is being continued from a previous conversation.",
            "Caveat: the messages below were generated by the user while running local commands.",
        ] {
            assert!(is_harness_injected(text), "{text}");
        }
    }

    #[test]
    fn is_case_insensitive_and_ignores_surrounding_whitespace() {
        assert!(is_harness_injected("  <TASK-NOTIFICATION> done"));
        assert!(is_harness_injected("\n<System-Reminder> hi"));
    }

    #[test]
    fn keeps_real_user_prompts_including_ones_that_mention_the_tags() {
        for text in [
            "fix the login bug",
            "why does <task-notification> show in the sidebar?",
            "",
            "   ",
            "<user_query>fix the bug</user_query>",
            "<div class=\"x\">pasted html</div>",
            "<script>alert(1)</script> — why is this flagged?",
            "<https://example.com/a-b> what is this?",
            "<foo-bar@example.com> sent me this",
            "<my-custom-element>pasted code",
            "<brand-new-harness-tag id=\"1\">payload",
            "<queued-notice>\nlater",
            "<channel>general</channel> explain this feed element",
        ] {
            assert!(!is_harness_injected(text), "{text}");
            assert_eq!(classify(text, &catalog), UserTurn::Keep, "{text}");
        }
    }

    #[test]
    fn classifies_harness_and_user_prefixes_in_multi_kb_pastes() {
        let large = format!(
            "<task-notification>done</task-notification>\n{}",
            "x".repeat(20_000)
        );
        assert!(is_harness_injected(&large));
        assert!(!is_harness_injected(&format!(
            "fix login {}",
            "y".repeat(20_000)
        )));
        // A multi-byte character at the head limit must not split.
        assert!(!is_harness_injected(&"é".repeat(400)));
    }

    #[test]
    fn restores_a_bash_line_as_typed_keeping_the_space_after_the_bang() {
        assert_eq!(
            bash_input_as_typed("<bash-input> gcloud auth login</bash-input>").as_deref(),
            Some("! gcloud auth login")
        );
        assert_eq!(
            bash_input_as_typed("<bash-input>ls -la</bash-input>").as_deref(),
            Some("!ls -la")
        );
        assert_eq!(
            classify("<bash-input>ls</bash-input>", &catalog),
            UserTurn::Shown("!ls".into())
        );
    }

    #[test]
    fn leaves_other_bash_text_alone() {
        for text in [
            "run <bash-input>ls</bash-input>",
            "<bash-input>ls</bash-input> and more",
            "<bash-stdout>ok</bash-stdout>",
            "<bash-input>a</bash-input><bash-input>b</bash-input>",
        ] {
            assert_eq!(bash_input_as_typed(text), None, "{text}");
        }
    }
}
